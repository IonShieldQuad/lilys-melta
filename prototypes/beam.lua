-- The beam's soft layers, as sprite prototypes.
--
-- `rendering.draw_line` can only draw a flat coloured quad -- no texture, no
-- gradient, no glow -- so every layer of the lance that has to *look* like heat is a
-- sprite the runtime draws and tints. Declaring them here (rather than pointing
-- `draw_sprite` at a file) is what SpritePath wants: the supported forms are a sprite
-- prototype name, "item/<name>", "entity/<name>", "utility/<name>" or "file/<path in
-- the current scenario>" -- a bare `__lilys-melta__/...` path is none of those, and
-- "file/" cannot reach a mod's own graphics folder.
--
-- The images are generated by graphics/beam/generate.py (white RGB, shape in the
-- alpha channel) and tinted at runtime with the burning fuel's colour, so one set of
-- five textures serves every fuel. Footprints at scale 1 are 32 px per tile:
--
--   beam-core    32 x 256  -> 1 x 8 tiles   soft cutting column, dies at the far end
--   beam-haze    64 x 256  -> 2 x 8 tiles   wide outer heat column
--   beam-glow    64 x 256  -> 2 x 8 tiles   bright gas around the cutting line
--   beam-cone    64 x 128  -> 2 x 4 tiles   muzzle blast, apex at the mouth
--   beam-tongue  32 x  64  -> 1 x 2 tiles   one boiling plasma tongue
--   beam-flare  128 x 128  -> 4 x 4 tiles   muzzle / impact burst
--   beam-spray   64 x 128  -> 2 x 4 tiles   dissolving plume past the end of the lance
--
-- The long ones are TALL, because `rendering.draw_sprite` rotates about the sprite's
-- centre and calls orientation 0 "north": the image is drawn unrotated with its
-- forward end at the top, and control.lua sets orientation = atan2(dx, -dy) / 2pi.

local function beam_sprite(name, file, width, height)
  return
  {
    type = "sprite",
    name = name,
    filename = "__lilys-melta__/graphics/entity/melta-beam/" .. file,
    width = width,
    height = height,
    -- mipmaps: the beam is drawn at up to ~1.5x its authored length and is seen from
    -- the map zoom levels, so let the engine keep clean minified copies. Linear
    -- min/mag filtering is the whole point -- a nearest-neighbour glow is a polygon.
    mipmap_count = 4,
    flags = {"mipmap", "linear-mip-level", "linear-minification", "linear-magnification"},
    -- ADDITIVE: Result = Active_RGB + Background_RGB, with the active colour
    -- premultiplied by its alpha -- so these layers add light to whatever is behind
    -- them (terrain, biters, the turret) instead of painting over it, and alpha still
    -- fades them out cleanly. That is what makes a wide low-alpha wash read as heat
    -- instead of as fog.
    blend_mode = "additive"
  }
end

data:extend
{
  beam_sprite("melta-beam-core", "beam-core.png", 32, 256),
  beam_sprite("melta-beam-spray", "beam-spray.png", 64, 128),
  beam_sprite("melta-beam-haze", "beam-haze.png", 64, 256),
  beam_sprite("melta-beam-glow", "beam-glow.png", 64, 256),
  beam_sprite("melta-beam-cone", "beam-cone.png", 64, 128),
  beam_sprite("melta-beam-tongue", "beam-tongue.png", 32, 64),
  beam_sprite("melta-beam-flare", "beam-flare.png", 128, 128)
}
